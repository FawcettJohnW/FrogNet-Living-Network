"""
resolv.py - manageResolv.bash ported. Builds /etc/resolv.conf:
  header / options / search domains / nameserver 127.0.0.1 / upstream (if any).
  [RESOLV_LOCAL_UPSTREAM_V1]: nothing else -- no self, no tunnel peers, no LAN neighbours, and no public resolver
  (it replaces [RESOLV_LOCAL_UPSTREAM_GOOGLE_V1], which always ended with 8.8.8.8: a second resolver behind the
  upstream, and an address the machine's own network may not allow). No upstream: 127.0.0.1 alone.

The upstream is live._dns_upstream (the default route's next hop; the same one dnsmasq_upstream.conf names).

NOTE: the oracle log does NOT dump resolv.conf, so this is proven STRUCTURALLY
(correct content for given inputs), not against a logged artifact.
"""
from __future__ import annotations


def build_resolv(local_domain: str, hostname: str, upstream: str) -> list[str]:
    """[RESOLV_LOCAL_UPSTREAM_V1] 127.0.0.1 and the upstream (if any) -- nothing else."""
    out = [
        "################################################",
        "# AUTO-GENERATED BY discovery.live (merge tail)",
        "# FrogNet Unified Routing Edition (2025)",
        "# DO NOT EDIT MANUALLY",
        "################################################",
        "",
        "# Section 1: options",
        "options timeout:1 attempts:1",
        "",
        "# Section 2: search domains",
    ]
    if local_domain and hostname:
        out.append(f"search {local_domain} {hostname}")
    out.append("")
    out += ["# Section 3: nameservers", "# Local FrogNet DNS", "nameserver 127.0.0.1", ""]
    if upstream and not upstream.startswith("127."):
        out.append(f"nameserver {upstream}")
    return out
