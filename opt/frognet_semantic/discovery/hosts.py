"""
hosts.py - /etc/hosts assembly, ported from mergeHostsAndResolv.bash stage_hosts
(lines 147-201), addHost (host-entry half), and selectNewDatabaseHost.

The host SET in /etc/hosts is the union of:
  - the local identity line (mergeHostsAndResolv local_identity)
  - bringup-registered direct peers (daemon BRINGUP_HOSTS_REGISTER -> addHost):
    this is why BABox is present even though wg0 is dead and it was never walked
  - discovery-discovered peers (walk -> addHostAndPropogate -> addHost)
All land in the frognet_hosts sentinel; stage_hosts normalizes + sort -u them.

[HOSTS_FORMAT_V2] every /etc/hosts 10.x line is "<ip> FrogNetHost.<net>" or
"<ip> FrogNetAdmin.<net>"; the self FrogNetHost line additionally gets the bare
"FrogNetHost" alias. Bare short names are stripped.

The route-install half of addHost is intentionally omitted: discovery calls
addHostAndPropogate with ping_host="" so addHost's route block never fires
(PING_HOST empty/0.0.0.0 -> skipped). The /24 routes are owned by promote.
"""
from __future__ import annotations

HOSTS_HEADER = [
    "################################################",
    "# AUTO-GENERATED BY mergeHostsAndResolv.bash   #",
    "################################################",
    "127.0.0.1 localhost",
]

# [FROGNETHOST_IS_NOT_LOOPBACK_V1] The bare alias "FrogNetHost" is NOT on the
# 127.0.0.1 line any more.
#
# It used to read "127.0.0.1 localhost FrogNetHost", while further down the
# same file the self line carries the alias too:
#
#     127.0.0.1   localhost FrogNetHost          <- first match wins
#     10.160.160.1 FrogNetHost.Seattle6 FrogNetHost
#
# Anything resolving the bare name got 127.0.0.1, because the loopback line
# sorts first and every resolver takes the first match. A peer told to reach
# "FrogNetHost" then talked to itself instead of the machine that owns the
# name, and the failure is silent -- the connection succeeds, to the wrong box.
#
# The alias belongs on the line that has the real address. _normalize already
# appends it there for ip == self_ip; this just stops the loopback line from
# claiming it first.


def derive_domain(hostname: str, append: str = "") -> str:
    """addHost domain derivation. 'BAMacBook' -> 'BAMacBook';
    'a.b' -> 'b'; bare name with append -> append.
    [DERIVE_DOMAIN_NONE_GUARD_V1] A None/empty name has no domain - return the
    append (or "") instead of crashing on .split()."""
    if not hostname:
        return append or ""
    name_part = hostname.split(".", 1)[0]
    domain_part = hostname.split(".", 1)[1] if "." in hostname else name_part
    if domain_part == name_part:
        return append or name_part
    return domain_part


def addhost_lines(host: str, host_path: str, append: str = "") -> list[str]:
    """The two frognet_hosts lines addHost writes for a peer:
        <.1> <domain> FrogNetHost.<domain>
        <.2> FrogNetAdmin.<domain>"""
    domain = derive_domain(host, append)
    admin_ip = host_path.rsplit(".", 1)[0] + ".2"
    return [
        f"{host_path} {domain} FrogNetHost.{domain}",
        f"{admin_ip} FrogNetAdmin.{domain}",
    ]


def reconcile_added(added, prior_names=None, logger=lambda s: None):
    """[HOSTS_AUTHORITATIVE_NAME_V1 / HOSTS_NAME_CHANGE_RUNAGAIN_V1]

    added       = list of (host, host_path, dev, authoritative) the walk recorded.
                  authoritative=True is the name a node returned for ITSELF via
                  echo (or the broker override) - the source of truth.
                  authoritative=False is a relayed vouch name (a neighbor's
                  getHosts entry, which may be the generic "FrogNetHost").
    prior_names = {host_path(.1): domain} parsed from the current /etc/hosts.

    Returns (lines, host_name_changed):
      lines             = the addhost_lines for the CHOSEN name per IP. Per IP an
                          authoritative name wins; a vouch name is a fallback only
                          when no echo named that peer. This is what removes the
                          duplicate "FrogNetHost.FrogNetHost" line for a peer also
                          reached by a direct echo.
      host_name_changed = True iff an authoritative name's domain differs from the
                          domain already in /etc/hosts for that IP (the node
                          changed names; the old name is deprecated). Only an
                          authoritative name can deprecate - a vouch never does.
    """
    auth_name: dict = {}      # host_path(.1) -> authoritative name
    vouch_name: dict = {}     # host_path(.1) -> relayed fallback name
    ip_order: list = []
    for host, host_path, _dev, is_auth in added:
        if host_path not in auth_name and host_path not in vouch_name:
            ip_order.append(host_path)
        if is_auth:
            auth_name[host_path] = host          # last authoritative wins (stable)
        else:
            vouch_name.setdefault(host_path, host)

    lines: list[str] = []
    for host_path in ip_order:
        name = auth_name.get(host_path) or vouch_name.get(host_path)
        # [NAMELESS_HOST_SKIP_V1] An echo-less authoritative entry (host="") with
        # no relayed vouch yields no name at all. A host line with no name is
        # useless and derive_domain(None) crashes, so skip it - reachability is
        # tracked separately; the name fills in once an echo or vouch supplies one.
        if not name:
            continue
        lines += addhost_lines(name, host_path)

    host_name_changed = False
    if prior_names:
        for host_path, name in auth_name.items():
            dom = derive_domain(name)
            prev = prior_names.get(host_path)
            # [BLANK_AUTH_NAME_GUARD_V1] A blank authoritative name carries no
            # information: the line-builder above already fell back to the vouch
            # name, so the real name stays in the file. Flagging host_name_changed
            # on an empty dom is a phantom rename - prev never equals "" so it
            # fires every pass and livelocks runAgain while /etc/hosts is unchanged.
            # Only a NON-EMPTY authoritative name may deprecate a prior name.
            if dom and prev is not None and prev != dom:
                host_name_changed = True
                logger(f"HOSTS_NAME_CHANGE ip={host_path} old={prev} new={dom} "
                       f"reason=authoritative_supersedes_deprecated_name")
    return lines, host_name_changed


def local_lines(eth0_ip: str, domain: str) -> list[str]:
    """mergeHostsAndResolv local_identity: 2-field local lines (no bare name;
    the FrogNetHost alias is appended during staging for the self line)."""
    admin_ip = eth0_ip.rsplit(".", 1)[0] + ".2"
    return [
        f"{eth0_ip} FrogNetHost.{domain}",
        f"{admin_ip} FrogNetAdmin.{domain}",
    ]


def _normalize(line: str, self_ip: str):
    """stage_hosts awk: keep the FrogNetHost./FrogNetAdmin. field; self
    FrogNetHost line gets a trailing 'FrogNetHost'."""
    parts = line.split()
    if not parts or not parts[0].startswith("10."):
        return None
    ip = parts[0]
    keep = ""
    for f in parts[1:]:
        if f.startswith("FrogNetHost.") or f.startswith("FrogNetAdmin."):
            keep = f
            break
    if not keep:
        return None
    if ip == self_ip and keep.startswith("FrogNetHost."):
        return f"{ip} {keep} FrogNetHost"
    return f"{ip} {keep}"


def build_etc_hosts(frognet_hosts_lines: list[str], self_ip: str) -> list[str]:
    """Reproduce stage_hosts output (header + 127 line + sort -u of normalized
    10.x lines). Lexical sort matches coreutils `sort` in C locale."""
    normalized = []
    for ln in frognet_hosts_lines:
        n = _normalize(ln, self_ip)
        if n is not None:
            normalized.append(n)
    block = sorted(set(normalized))   # sort -u (lexical)
    return list(HOSTS_HEADER) + block


def _ip_to_int(ip: str) -> int:
    a, b, c, d = (int(x) for x in ip.split("."))
    return (a << 24) | (b << 16) | (c << 8) | d


def _num(v, default=0.0):
    """[RANK_NUM_GUARD_V1] Coerce one capability field to a number, tolerating a
    malformed publish - a nested object/list/None/garbage where a scalar was
    expected (e.g. mem_available_kb arriving as a dict, which crashed the whole
    merge in select_database_host._rank). Never raises: a bad field degrades that
    one candidate's score, it does not take the merge down. bool is rejected (it
    is an int subclass but never a meaningful perf number here)."""
    if isinstance(v, bool):
        return default
    if isinstance(v, (int, float)):
        return v
    if isinstance(v, str):
        try:
            return float(v)
        except ValueError:
            return default
    return default


