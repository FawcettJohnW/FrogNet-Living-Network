# set -x

. /usr/local/bin/mapInterfaces

mkdir -p /etc/sentinels
touch /etc/sentinels/frog_resolv.conf

LOCAL_DOMAIN="$(grep -h '^domain=' /etc/dnsmasq.d/opts_only.conf | sed 's/domain=//' | head -n1 || true)"
HOSTNAME="$(hostname || true)"
HOSTDOMAIN="$(echo "$HOSTNAME" | cut -d. -f2 || true)"
[[ -z "${LOCAL_DOMAIN:-}" ]] && LOCAL_DOMAIN="$HOSTDOMAIN"

NEW="/etc/sentinels/new_resolv.conf"
: > "$NEW"

echo '################################################' >> "$NEW"
echo '# AUTO-GENERATED BY manageResolv.bash' >> "$NEW"
echo '# FrogNet Unified Routing Edition (2025)' >> "$NEW"
echo '# DO NOT EDIT MANUALLY' >> "$NEW"
echo '################################################' >> "$NEW"
echo '' >> "$NEW"

echo '# Section 1: options' >> "$NEW"
echo 'options timeout:1 attempts:1' >> "$NEW"
echo '' >> "$NEW"

echo '# Section 2: search domains' >> "$NEW"
if [[ -n "${LOCAL_DOMAIN:-}" && -n "${HOSTNAME:-}" ]]; then
  echo "search ${LOCAL_DOMAIN} ${HOSTNAME}" >> "$NEW"
fi
echo '' >> "$NEW"

echo '# Section 3: nameservers' >> "$NEW"
echo '# Local FrogNet DNS' >> "$NEW"
echo 'nameserver 127.0.0.1' >> "$NEW"
echo '' >> "$NEW"

EXIT_SENT="/etc/sentinels/exit_host.tsv"

# Prefer exit_host.tsv written by fixDefaultRoute:
# format: exit_host<TAB>next_hop<TAB>dev<TAB>exit_gateway<TAB>nameservers_csv
WAN_NS=""
if [[ -s "$EXIT_SENT" ]]; then
  WAN_NS="$(awk -F'\t' 'NF>=5 {print $5}' "$EXIT_SENT" | head -n1 | tr ',' ' ' || true)"
fi

# Fallback heuristic (old behavior) ONLY if exit_host.tsv absent
if [[ -z "${WAN_NS// /}" ]]; then
  WAN_NS="$(ip r | awk '/via/ && $1 !~ /^10\./ && $3 ~ /^([0-9]+\.){3}[0-9]+$/ {print $3}' || true)"
fi

# Emit WAN nameservers (dedupe)
if [[ -n "${WAN_NS// /}" ]]; then
  echo '# WAN fallback DNS' >> "$NEW"
  # unique, stable order
  for ip in $(echo "$WAN_NS" | tr ' ' '\n' | awk NF | awk '!seen[$0]++'); do
    echo "nameserver $ip" >> "$NEW"
  done
fi

# [DNS_NEXTHOP_ONLY_V1] dnsmasq forwards to the NEXT HOP on the default route and
# nobody else -- no lease nameservers, no hardcoded 8.8.8.8, no unbound. The next
# hop is field 2 of exit_host.tsv, written by fixDefaultRoute (the same gateway
# the default route points at). dnsmasq is configured resolv-file=<this> with
# no-resolv UNSET, so its sole upstream is whatever we write here.
#
# The next hop may be a WAN gateway (edge node) or a peer's 10.x .1 (mesh-exit
# node): forward to it either way, because DNS chains along the default route the
# same way packets do. Empty when there is no default route -> no external DNS,
# the honest state for an unmerged node. Never our own dnsmasq (127.x -> loop).
DNSMASQ_UP="/etc/sentinels/dnsmasq_upstream.conf"
DNU_NEW="${DNSMASQ_UP}.new"
NEXT_HOP=""
if [[ -s "$EXIT_SENT" ]]; then
  NEXT_HOP="$(awk -F'\t' 'NR==1{print $2}' "$EXIT_SENT" | tr -d '[:space:]')"
fi
: > "$DNU_NEW"
# Forward to the next hop, 10.x or not. DNS follows the default route hop by hop,
# exactly as packets do: a mesh-exit node's next hop is a peer's .1, that peer
# runs dnsmasq and forwards to ITS next hop, and so on to the WAN edge. The only
# address we never write is our own dnsmasq (127.x) -- that would be a self-loop.
# Empty next hop -> empty file -> no external DNS, which is correct for a node
# with no default route yet.
if [[ -n "$NEXT_HOP" && "$NEXT_HOP" != 127.* ]]; then
  echo "nameserver $NEXT_HOP" >> "$DNU_NEW"
fi
if ! cmp -s "$DNU_NEW" "$DNSMASQ_UP" 2>/dev/null; then
  mv -f "$DNU_NEW" "$DNSMASQ_UP"
  chmod 644 "$DNSMASQ_UP"
  pkill -HUP -x dnsmasq 2>/dev/null || systemctl reload dnsmasq 2>/dev/null || true
  /usr/local/bin/debugTag "manageResolv: dnsmasq upstream -> ${NEXT_HOP:-<none>}"
else
  rm -f "$DNU_NEW"
fi

# Commit only if changed
if cmp -s "$NEW" /etc/resolv.conf; then
  /usr/local/bin/debugTag "manageResolv: no changes"
  exit 0
fi

cp "$NEW" /etc/resolv.conf
chmod 644 /etc/resolv.conf

/usr/local/bin/debugTag "manageResolv: updated resolv.conf"
exit 0

