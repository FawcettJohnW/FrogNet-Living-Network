# frognet-apache-bind.sh - [APACHE_LAN_BIND_V1]
#
# Write /etc/apache2/ports.conf so Apache listens on the node's FrogNet address
# and nowhere else.
#
# WHY THIS EXISTS. The docroot holds two endpoints that take no password:
# api.php (reads and writes the database) and frognet_setup_v4_api.php (calls
# root helpers). That is deliberate - the FrogNet LAN is the trust boundary and
# everyone on it is trusted. But the installer previously wrote a bare
#
#     Listen 8080
#
# which binds every interface on the box: the FrogNet LAN, wg0 once the pond is
# up, and whatever upstream network the setup page's own connect-wifi action
# joined. So the boundary the design relied on was documented in a comment and
# enforced nowhere. This script makes the socket match the doctrine.
#
# The address is resolved at Apache start rather than at install time, because
# the FrogNet IP is not known during install (phase B removes gateways.conf) and
# can change afterwards via apply-identity or change_pond.
#
# [NO_FALLBACK_V1] If the FrogNet address cannot be determined we bind loopback,
# not 0.0.0.0. A node whose dashboard is unreachable is a visible problem with a
# one-line log entry; a node silently serving the setup API to a hotel network
# is not.

set -uo pipefail

PORTS_CONF="${APACHE_PORTS_CONF:-/etc/apache2/ports.conf}"
GATEWAYS_CONF="${FROGNET_GATEWAYS_CONF:-/etc/frognet/gateways.conf}"
LOG_TAG="frognet-apache-bind"

log() {
    echo "$(date '+%Y-%m-%d %H:%M:%S') [$LOG_TAG] $*"
    logger -t "$LOG_TAG" "$*" 2>/dev/null || true
}

# The FrogNet address, in order of authority:
#   1. GATEWAY_IP from gateways.conf - what frognet_fixup.sh wrote for this node
#   2. the first 10.x address actually configured on an interface
resolve_bind_addr() {
    local ip=""

    if [[ -f "$GATEWAYS_CONF" ]]; then
        ip=$(grep -m1 '^GATEWAY_IP=' "$GATEWAYS_CONF" 2>/dev/null \
             | cut -d= -f2- | tr -d '"[:space:]')
        if [[ "$ip" =~ ^10\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            printf '%s' "$ip"; return 0
        fi
    fi

    ip=$(ip -4 -o addr show scope global 2>/dev/null \
         | awk '{print $4}' | cut -d/ -f1 | grep -m1 '^10\.' || true)
    if [[ "$ip" =~ ^10\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        printf '%s' "$ip"; return 0
    fi

    return 1
}

BIND_ADDR="$(resolve_bind_addr || true)"
if [[ -z "$BIND_ADDR" ]]; then
    log "NO_FROGNET_ADDRESS - no GATEWAY_IP in $GATEWAYS_CONF and no 10.x address on any interface."
    log "                     Binding 127.0.0.1 only. The dashboard and setup page will be"
    log "                     unreachable from the LAN until this node has its FrogNet address."
    BIND_ADDR="127.0.0.1"
fi

# [APACHE_LAN_BIND_V1] 8443 and 443 are deliberately absent. The SSL vhosts they
# served (frognet-ssl.conf) are no longer enabled: they carried the same
# unauthenticated docroot on every interface, and the certificate they used is a
# shared universal cert. Re-adding a TLS listener is fine - bind it to
# $BIND_ADDR here the same way, and give it a per-node certificate.
TMP="$(mktemp "${PORTS_CONF}.XXXXXX")" || exit 1
cat > "$TMP" <<PORTS
# GENERATED by /usr/local/bin/frognet-apache-bind.sh - do not edit.
# [APACHE_LAN_BIND_V1] Regenerated on every apache2 start; edits are lost.
#
# The docroot serves unauthenticated endpoints by design (see api.php and
# frognet_setup_v4_api.php). They are safe only while this socket is reachable
# from the FrogNet LAN alone. A bare "Listen 8080" would also expose them on
# wg0 and on any upstream WiFi this node has joined.
Listen ${BIND_ADDR}:8080
PORTS

if [[ -f "$PORTS_CONF" ]] && cmp -s "$TMP" "$PORTS_CONF"; then
    rm -f "$TMP"
    exit 0
fi

chmod 644 "$TMP"
mv -f "$TMP" "$PORTS_CONF"
log "BOUND ${BIND_ADDR}:8080 (was: all interfaces)"
exit 0
